-- ---------- Who may call what ----------
do $$
declare f text;
begin
  foreach f in array array[
    'register_student(jsonb)', 'import_students(jsonb)', 'apply_section_allocation(jsonb,jsonb)',
    'change_student_stream(uuid,uuid)', 'set_student_status(uuid,student_status)']
  loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  revoke all on function public._register_student(jsonb) from public, anon, authenticated;
end $$;
