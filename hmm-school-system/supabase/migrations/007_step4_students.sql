-- ---------- 1. Student ID ----------
-- Alphabet has 31 characters (no 0, O, 1, I, L). Check character = weighted sum mod 31.
create or replace function public.student_code_check(p_year int, p_rand text) returns text
language plpgsql immutable as $$
declare
  alphabet constant text := '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
  total int := p_year;
  idx int;
begin
  for i in 1..length(p_rand) loop
    idx := position(substr(p_rand, i, 1) in alphabet) - 1;
    if idx < 0 then return null; end if;
    total := total + idx * i;
  end loop;
  return substr(alphabet, (total % 31) + 1, 1);
end $$;

create or replace function public.is_valid_student_code(p_code text) returns boolean
language plpgsql immutable as $$
declare m text[];
begin
  m := regexp_match(upper(coalesce(p_code, '')), '^HMM-([0-9]{4})-([2-9A-HJKMNP-Z]{5})-([2-9A-HJKMNP-Z])$');
  if m is null then return false; end if;
  return public.student_code_check(m[1]::int, m[2]) = m[3];
end $$;

create or replace function public.generate_student_code() returns text
language plpgsql security definer set search_path = public, extensions as $$
declare
  alphabet constant text := '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
  yr int;
  r text;
  code text;
  b int;
  tries int := 0;
begin
  select year_ec into yr from public.academic_years where is_current limit 1;
  if yr is null then
    yr := extract(year from current_date)::int
          - case when current_date >= make_date(extract(year from current_date)::int, 9, 11) then 7 else 8 end;
  end if;
  loop
    r := '';
    while length(r) < 5 loop
      b := get_byte(gen_random_bytes(1), 0);
      if b < 248 then r := r || substr(alphabet, (b % 31) + 1, 1); end if;   -- 248 = 31 * 8, keeps it uniform
    end loop;
    code := 'HMM-' || yr || '-' || r || '-' || public.student_code_check(yr, r);
    exit when not exists (select 1 from public.students where student_code = code);
    tries := tries + 1;
    if tries > 30 then raise exception 'Could not generate a unique student ID'; end if;
  end loop;
  return code;
end $$;

-- The ID is always generated by the database and can never be changed.
create or replace function public.students_code_guard() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    new.student_code := public.generate_student_code();
  elsif new.student_code is distinct from old.student_code then
    raise exception 'The student ID cannot be changed';
  end if;
  return new;
end $$;
create trigger students_code_guard before insert or update on public.students
for each row execute function public.students_code_guard();

-- ---------- 2. Rules on enrollments ----------
-- 'general' (Grades 9-10) is treated the same as "no stream".
create or replace function public.stream_key(p_stream uuid) returns uuid
language sql stable as $$
  select id from public.streams where id = p_stream and code <> 'general'
$$;

create or replace function public.check_enrollment_rules() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  g_no smallint; st_code text; sec record; stu record; cnt int;
begin
  select number into g_no from public.grades where id = new.grade_id;
  if new.stream_id is not null then select code into st_code from public.streams where id = new.stream_id; end if;

  if g_no <= 10 then
    if st_code is not null and st_code <> 'general' then
      raise exception 'Grades 9 and 10 do not have a Natural or Social Science stream';
    end if;
  elsif st_code is null or st_code = 'general' then
    raise exception 'Grades 11 and 12 need a Natural or Social Science stream';
  end if;

  if tg_op = 'INSERT' then
    select * into stu from public.students where id = new.student_id;
    if new.status = 'new' and g_no = 9
       and (nullif(trim(coalesce(stu.previous_school, '')), '') is null or stu.grade8_exam_result is null) then
      raise exception 'Grade 9 entrants need the previous school and the Grade 8 exam result';
    end if;
    if new.status = 'transfer_in'
       and (nullif(trim(coalesce(stu.transfer_certificate_no, '')), '') is null
            or nullif(trim(coalesce(stu.previous_grade, '')), '') is null) then
      raise exception 'Transfer students need the transfer certificate number and the previous grade';
    end if;
  end if;

  if new.section_id is not null then
    select * into sec from public.sections where id = new.section_id;
    if sec.academic_year_id <> new.academic_year_id or sec.grade_id <> new.grade_id
       or public.stream_key(sec.stream_id) is distinct from public.stream_key(new.stream_id) then
      raise exception 'The section does not match the academic year, grade and stream';
    end if;
    if sec.capacity is not null
       and coalesce(current_setting('hmm.bulk_allocation', true), '') <> 'on'
       and (tg_op = 'INSERT' or new.section_id is distinct from old.section_id) then
      select count(*) into cnt from public.enrollments
        where section_id = new.section_id and id <> new.id and status not in ('withdrawn');
      if cnt >= sec.capacity then
        raise exception 'Section % is full (capacity %). Raise the capacity or use another section', sec.name, sec.capacity;
      end if;
    end if;
  end if;
  return new;
end $$;
create trigger enrollments_rules before insert or update on public.enrollments
for each row execute function public.check_enrollment_rules();

-- A student must always keep at least one guardian.
create or replace function public.guard_last_guardian() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from public.students where id = old.student_id)
     and not exists (select 1 from public.student_guardians
                     where student_id = old.student_id and guardian_id <> old.guardian_id) then
    raise exception 'A student must keep at least one guardian';
  end if;
  return old;
end $$;
create trigger student_guardians_keep_one before delete on public.student_guardians
for each row execute function public.guard_last_guardian();

-- ---------- 3. Registration (one student, all or nothing) ----------
create or replace function public._register_student(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  s jsonb := p->'student';
  e jsonb := p->'enrollment';
  g jsonb;
  v_student uuid; v_code text; v_guardian uuid; v_dob date;
  v_any_phone boolean := false; v_primary_set boolean := false; n int := 0;
begin
  if s is null or jsonb_typeof(s) <> 'object' then raise exception 'Missing student data'; end if;
  if coalesce(trim(s->>'first_name'), '') = '' or coalesce(trim(s->>'father_name'), '') = ''
     or coalesce(trim(s->>'grandfather_name'), '') = '' then
    raise exception 'First, father''s and grandfather''s names are required';
  end if;
  if (s->>'sex') is null or (s->>'sex') not in ('male', 'female') then raise exception 'Sex is required'; end if;
  begin v_dob := (s->>'date_of_birth')::date; exception when others then v_dob := null; end;
  if v_dob is null or v_dob < date '1970-01-01' or v_dob > current_date then
    raise exception 'A valid date of birth is required';
  end if;
  if jsonb_typeof(p->'guardians') is distinct from 'array' or jsonb_array_length(p->'guardians') = 0 then
    raise exception 'At least one guardian is required';
  end if;
  for g in select * from jsonb_array_elements(p->'guardians') loop
    if coalesce(trim(g->>'full_name'), '') = '' or coalesce(trim(g->>'relationship'), '') = '' then
      raise exception 'Every guardian needs a name and a relationship';
    end if;
    if coalesce(trim(g->>'phone'), '') <> '' then v_any_phone := true; end if;
  end loop;
  if not v_any_phone then raise exception 'At least one guardian needs a phone number'; end if;

  insert into public.students (
    first_name, father_name, grandfather_name, first_name_am, father_name_am, grandfather_name_am,
    sex, date_of_birth, date_of_birth_ec, place_of_birth, nationality, mother_full_name, health_condition,
    region, zone, woreda, kebele, house_number, phone,
    previous_school, previous_grade, transfer_certificate_no, grade8_exam_result, documents, student_code
  ) values (
    trim(s->>'first_name'), trim(s->>'father_name'), trim(s->>'grandfather_name'),
    nullif(trim(s->>'first_name_am'), ''), nullif(trim(s->>'father_name_am'), ''), nullif(trim(s->>'grandfather_name_am'), ''),
    (s->>'sex')::sex_type, v_dob, nullif(trim(s->>'date_of_birth_ec'), ''),
    nullif(trim(s->>'place_of_birth'), ''), coalesce(nullif(trim(s->>'nationality'), ''), 'Ethiopian'),
    nullif(trim(s->>'mother_full_name'), ''), nullif(trim(s->>'health_condition'), ''),
    nullif(trim(s->>'region'), ''), nullif(trim(s->>'zone'), ''), nullif(trim(s->>'woreda'), ''),
    nullif(trim(s->>'kebele'), ''), nullif(trim(s->>'house_number'), ''), nullif(trim(s->>'phone'), ''),
    nullif(trim(s->>'previous_school'), ''), nullif(trim(s->>'previous_grade'), ''),
    nullif(trim(s->>'transfer_certificate_no'), ''), nullif(s->>'grade8_exam_result', '')::numeric,
    coalesce(s->'documents', '{}'::jsonb), 'pending'
  ) returning id, student_code into v_student, v_code;

  for g in select * from jsonb_array_elements(p->'guardians') loop
    n := n + 1;
    v_guardian := nullif(g->>'id', '')::uuid;
    if v_guardian is null and coalesce(trim(g->>'phone'), '') <> '' then
      select id into v_guardian from public.guardians
        where phone = trim(g->>'phone') and lower(trim(full_name)) = lower(trim(g->>'full_name')) limit 1;
    end if;
    if v_guardian is null then
      insert into public.guardians (full_name, phone, occupation, address)
      values (trim(g->>'full_name'), nullif(trim(g->>'phone'), ''), nullif(trim(g->>'occupation'), ''), nullif(trim(g->>'address'), ''))
      returning id into v_guardian;
    end if;
    insert into public.student_guardians (student_id, guardian_id, relationship, is_primary, is_emergency_contact)
    values (v_student, v_guardian, trim(g->>'relationship'),
            coalesce((g->>'is_primary')::boolean, false) and not v_primary_set,
            coalesce((g->>'is_emergency_contact')::boolean, false))
    on conflict (student_id, guardian_id) do nothing;
    if coalesce((g->>'is_primary')::boolean, false) then v_primary_set := true; end if;
  end loop;
  if not v_primary_set then
    update public.student_guardians set is_primary = true
    where student_id = v_student and guardian_id = (select guardian_id from public.student_guardians where student_id = v_student limit 1);
  end if;

  if e is not null and jsonb_typeof(e) = 'object' and coalesce(e->>'academic_year_id', '') <> '' then
    insert into public.enrollments (student_id, academic_year_id, grade_id, section_id, stream_id, status)
    values (v_student, (e->>'academic_year_id')::uuid, (e->>'grade_id')::uuid,
            nullif(e->>'section_id', '')::uuid, nullif(e->>'stream_id', '')::uuid,
            coalesce(nullif(e->>'status', ''), 'new')::enrollment_status);
  end if;
  return jsonb_build_object('student_id', v_student, 'student_code', v_code);
end $$;

create or replace function public.register_student(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(array['system_admin', 'registrar']::app_role[]) then raise exception 'Not allowed'; end if;
  return public._register_student(p);
end $$;

-- Import: each row is its own all-or-nothing unit. Returns one result per row, in order.
create or replace function public.import_students(p_rows jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r jsonb; out jsonb := '[]'::jsonb; res jsonb;
begin
  if not public.has_role(array['system_admin', 'registrar']::app_role[]) then raise exception 'Not allowed'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    begin
      res := public._register_student(r);
      out := out || jsonb_build_array(jsonb_build_object('ok', true) || res);
    exception when others then
      out := out || jsonb_build_array(jsonb_build_object('ok', false, 'error', sqlerrm));
    end;
  end loop;
  return out;
end $$;

-- ---------- 4. Allocation, stream change, status change ----------
-- Saves an approved allocation in ONE step: creates the proposed new sections, then moves students.
-- p_new_sections: [{key, academic_year_id, grade_id, stream_id, shift, name, capacity}]
-- p_moves:        [{enrollment_id, section_id | section_key | null}]
-- If anything is wrong (for example a section ends up over its capacity) nothing is saved.
create or replace function public.apply_section_allocation(p_new_sections jsonb, p_moves jsonb) returns integer
language plpgsql security definer set search_path = public as $$
declare
  ns jsonb; m jsonb; n int := 0; v_id uuid; v_sec uuid;
  keymap jsonb := '{}'::jsonb;
  bad record;
begin
  if not public.has_role(array['system_admin', 'registrar']::app_role[]) then raise exception 'Not allowed'; end if;

  for ns in select * from jsonb_array_elements(coalesce(p_new_sections, '[]'::jsonb)) loop
    insert into public.sections (academic_year_id, grade_id, stream_id, shift, name, capacity)
    values ((ns->>'academic_year_id')::uuid, (ns->>'grade_id')::uuid, nullif(ns->>'stream_id', '')::uuid,
            (ns->>'shift')::shift_type, ns->>'name', nullif(ns->>'capacity', '')::smallint)
    returning id into v_id;
    keymap := keymap || jsonb_build_object(ns->>'key', v_id::text);
  end loop;

  perform set_config('hmm.bulk_allocation', 'on', true);
  for m in select * from jsonb_array_elements(coalesce(p_moves, '[]'::jsonb)) loop
    v_sec := coalesce(nullif(m->>'section_id', '')::uuid, nullif(keymap->>(m->>'section_key'), '')::uuid);
    update public.enrollments set section_id = v_sec where id = (m->>'enrollment_id')::uuid;
    n := n + 1;
  end loop;
  perform set_config('hmm.bulk_allocation', 'off', true);

  -- capacity is checked once, on the final result
  select s.name, s.capacity, count(e.id) as cnt into bad
  from public.sections s join public.enrollments e on e.section_id = s.id and e.status <> 'withdrawn'
  where s.capacity is not null
  group by s.id, s.name, s.capacity
  having count(e.id) > s.capacity limit 1;
  if found then
    raise exception 'Section % would have % students but its capacity is %', bad.name, bad.cnt, bad.capacity;
  end if;
  return n;
end $$;

create or replace function public.change_student_stream(p_enrollment uuid, p_stream uuid) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(array['system_admin', 'registrar', 'director', 'vice_director']::app_role[]) then
    raise exception 'Not allowed';
  end if;
  update public.enrollments e
  set stream_id = p_stream,
      section_id = case when public.stream_key((select s.stream_id from public.sections s where s.id = e.section_id))
                             is not distinct from public.stream_key(p_stream) then e.section_id else null end
  where e.id = p_enrollment;
end $$;

create or replace function public.set_student_status(p_student uuid, p_status student_status) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.has_role(array['system_admin', 'registrar']::app_role[]) then raise exception 'Not allowed'; end if;
  update public.students set status = p_status where id = p_student;
  if p_status in ('withdrawn', 'transferred_out') then
    update public.enrollments set status = 'withdrawn'
    where student_id = p_student and academic_year_id in (select id from public.academic_years where is_current);
  end if;
end $$;

-- ---------- 5. Duplicate finder and age limits ----------
create or replace function public.find_duplicate_students(p_first text, p_father text, p_grandfather text, p_dob date)
returns table (id uuid, student_code text, first_name text, father_name text, grandfather_name text, date_of_birth date)
language sql stable as $$
  select s.id, s.student_code, s.first_name, s.father_name, s.grandfather_name, s.date_of_birth
  from public.students s
  where lower(trim(s.first_name)) = lower(trim(p_first))
    and lower(trim(s.father_name)) = lower(trim(p_father))
    and lower(trim(s.grandfather_name)) = lower(trim(p_grandfather))
    and s.date_of_birth = p_dob
$$;

